// NODE_PATH=<Playwright location> node tests/check_design.cjs; synthetic camera only.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless:true, args:['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream']});
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  fs.mkdirSync('logs/design', {recursive:true});
  try {
    await page.goto(process.env.APP_URL || 'http://localhost:8511');
    await page.getByRole('button', {name:'START',exact:true}).waitFor({timeout:90000});
    await page.evaluate(() => document.fonts.ready);
    assert(await page.evaluate(() => document.fonts.check('14px Inter')), 'Inter not loaded');
    await page.getByRole('link', {name:/Help/}).hover();
    const tip = page.locator('.nav-tip:visible');
    await tip.waitFor();
    const tipBox = await tip.boundingBox();
    const railBox = await page.getByTestId('stSidebar').boundingBox();
    assert(tipBox.x >= railBox.x + railBox.width, 'Tooltip overlaps navigation icons');
    await page.getByTestId('stMain').hover();
    await page.screenshot({path:'logs/design/isyarat-desktop.png',fullPage:true});
    assert(await page.getByTestId('stMain').evaluate(e => e.scrollHeight <= e.clientHeight + 2), 'Default desktop camera page requires scrolling');
    assert(!(await page.getByTestId('stSidebarCollapseButton').isVisible()), 'Native collapse arrow is visible');
    await page.getByRole('button', {name:'START',exact:true}).click();
    await page.waitForFunction(() => {
      return [...document.querySelectorAll('*')].some(e => e.shadowRoot?.querySelector('video')?.srcObject?.active);
    });
    const video = page.locator('video');
    const track = await video.evaluateHandle(v => v.srcObject.getVideoTracks()[0]);
    await page.waitForFunction(() => [...document.querySelectorAll('*')].some(e => {
      const v = e.shadowRoot?.querySelector('video');
      return v?.videoWidth && Math.abs(v.clientWidth / v.clientHeight - v.videoWidth / v.videoHeight) < 0.02;
    }));
    await page.getByRole('button', {name:/Expand navigation/}).click();
    await page.getByRole('button', {name:/Collapse navigation/}).waitFor();
    assert(await track.evaluate(t => t.readyState === 'live'), 'Expanding navigation stopped camera');
    await page.getByRole('button', {name:/Collapse navigation/}).click();
    await page.getByRole('button', {name:/Expand navigation/}).waitFor();
    assert(await track.evaluate(t => t.readyState === 'live'), 'Collapsing navigation stopped camera');
    await page.getByRole('button', {name:'Mirror preview',exact:true}).click();
    await page.getByRole('button', {name:'Show hand landmarks',exact:true}).click();
    assert(await track.evaluate(t => t.readyState === 'live'), 'Icon toggles stopped camera');
    await page.getByRole('slider', {name:'Confidence (%)'}).press('ArrowRight');
    assert(await track.evaluate(t => t.readyState === 'live'), 'Settings stopped camera');
    await page.getByRole('link', {name:'Text to graphics'}).click();
    await page.getByRole('textbox', {name:'Text to spell',exact:true}).fill('IQ AKU!');
    await page.getByRole('textbox', {name:'Text to spell',exact:true}).press('Enter');
    await page.getByText('BISINDO · I · Word 1', {exact:true}).waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('.letter-grid img')].every(i => i.complete && i.naturalWidth > 0));
    assert(await page.locator('.letter-grid img').count() === 5, 'BISINDO assets missing');
    await page.getByRole('radio', {name:'SIBI',exact:true}).click();
    await page.getByText('SIBI · I · Word 1', {exact:true}).waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('.letter-grid img')].every(i => i.complete && i.naturalWidth > 0));
    assert(await page.locator('.letter-grid img').count() === 5, 'SIBI assets missing');
    assert(await page.getByTestId('stMain').evaluate(e => e.scrollHeight <= e.clientHeight + 2), 'Graphics page requires desktop scroll');
    await page.getByRole('textbox', {name:'Text to spell',exact:true}).fill('ABCDEFGHIJK');
    await page.getByRole('textbox', {name:'Text to spell',exact:true}).press('Enter');
    await page.getByText('SIBI · A · Word 1', {exact:true}).waitFor();
    assert(await page.locator('.letter-grid img').count() === 8, 'First gallery page skips letters');
    await page.getByRole('textbox', {name:'Text to spell',exact:true}).fill('IQ AKU!');
    await page.getByRole('textbox', {name:'Text to spell',exact:true}).press('Enter');
    await page.getByText('SIBI · I · Word 1', {exact:true}).waitFor();
    assert(await track.evaluate(t => t.readyState === 'ended'), 'Navigation leaked camera track');
    await page.screenshot({path:'logs/design/grafis-desktop.png',fullPage:true});
    const mobile = await browser.newPage({viewport:{width:390,height:844}});
    await mobile.goto((process.env.APP_URL || 'http://localhost:8511') + '/grafis');
    await mobile.getByRole('textbox', {name:'Text to spell',exact:true}).fill('IQ AKU!');
    await mobile.getByRole('textbox', {name:'Text to spell',exact:true}).press('Enter');
    await mobile.getByText('BISINDO · I · Word 1', {exact:true}).waitFor();
    await mobile.screenshot({path:'logs/design/grafis-mobile.png',fullPage:true});
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow');
    await mobile.goto(process.env.APP_URL || 'http://localhost:8511');
    await mobile.getByRole('button', {name:'START',exact:true}).waitFor({timeout:90000});
    await mobile.screenshot({path:'logs/design/isyarat-mobile.png',fullPage:true});
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Camera page mobile overflow');
    const rail = await mobile.getByTestId('stSidebar').boundingBox();
    const main = await mobile.getByTestId('stMain').boundingBox();
    assert(rail.x + rail.width <= main.x, 'Mobile sidebar overlaps workspace');
    await mobile.close();
    await page.getByRole('link', {name:/Help/}).click();
    await page.getByRole('heading', {name:'Help',exact:true}).waitFor();
    await page.screenshot({path:'logs/design/panduan-desktop.png',fullPage:true});
    assert.deepEqual(errors, []);
    console.log('PASS: font, desktop/mobile screenshots, settings preserve camera, navigation closes track, no JS errors.');
  } finally {
    await browser.close();
  }
})().catch(error => {console.error(error); process.exitCode=1;});
